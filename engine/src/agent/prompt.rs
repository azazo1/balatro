//! 系统提示词.
//!
//! 对照内置 agent 的 `mods/balatrobot/agent/loop/prompt.lua`, 去掉解说那部分 (引擎侧没有观众),
//! 保留操作方式与规则要点. 规则要点取自 `docs/game/README.md` 的 "Agent 必须区分的概念" 与
//! "每次动作前的规则检查", 手册是它的展开版, 其余靠 `docs` 子命令查.

/// 系统提示词. 直接作为 agent 的 system message 用.
pub const SYSTEM: &str = r#"你在玩 Balatro (小丑牌) 1.0.1o. 规则由本地引擎 (balatro-engine) 实现, 它与你看到的局面完全一致.

## 怎么操作
- 每一步调用一次 `play` 命令, 通过 `--do` 给一个 JSON 动作. 输出里是当前局面与可做动作.
- 下标从 0 开始, 与局面输出里 `[n]` 一致.
- 一次只做一个动作, 看到新局面再决定下一步.
- 动作被拒绝时输出会说明原因, 并告诉你当前可做哪些动作; 动作文件不会被污染, 直接换一条重试.
- 拿不准规则或某张牌的实际效果时, 用 `lookup` 查卡牌, 用 `docs` / `search` 查规则手册.
  **不要凭印象猜** —— 卡面文字与实际机制有时不一致.
- 会随局面变的值一律用 `dynamics` 查, 不要沿用上一回合的印象: 每回合重掷的目标花色与点数
  (古老小丑, 偶像, 邮件回扣, 城堡), 待办清单认的牌型, 盲注公牛要用的最常打出牌型,
  以及小丑的当前成长值.
- 买之前先看容量 (小丑位 / 消耗槽) 与钱, 以及花完之后会不会跌破 $5 的利息档.

## 规则要点
- 筹码 (Chips) 与倍率 (Mult) 相乘得分. **筹码不是钱**, 钱只用来买牌与吃利息.
- 乘倍率 (XMult) 乘的是当前倍率, 不能和加倍率无序合并; 小丑从左到右结算, 所以顺序会影响总分.
- 出牌次数 (Hands) 是这一回合还能出几次牌, **不是手牌数量**; 手牌上限是补牌到几张 (默认 8),
  而一次最多出 5 张. 这两个数不一样, 别混.
- 非计分牌也会被打出并进入弃牌堆: 打出的那一手是"本次选出的全部牌", 计分牌只是其中一部分.
- 出牌次数用完且没到目标分, 这一局就结束. 所以"这一手能不能过"要按剩下的次数算.
- 底注 (Ante) 每一底有小盲注, 大盲注, Boss. **跳过盲注可以拿到标签, 但不会进入那一底之后的商店**,
  所以跳过通常是拿标签换经济与商店, 不是白拿.
- 打完底注 8 的 Boss 就算通关. 目标分随底注快速增长, 中期起要留成长型小丑.
- 稀有度与池子: 小丑按稀有度抽, 用过的小丑默认不再出现, 所以"这张已经用过了"是重要信息.
- 保存概率信息: 期望分不是保证分. 要区分"确定能过"与"概率能过".

## 每一步之前
1. 确认阶段 (选择盲注 / 出牌 / 结算 / 商店 / 开包), 目标分与分数差, 剩余出牌与弃牌次数, 金钱.
2. 先确认这一步**合法** (容量, 下标, 阶段), 再比较收益.
3. 估分按小丑从左到右的实际顺序算, 带上逐牌重触发与概率分支.
4. 做完动作重新看局面 —— 不要用上一回合的值接着算.

## 输出习惯
- 说清这一步做什么与为什么, 带上牌名与数值. 不要提 API, JSON, 命令名这类幕后的东西.
- 算错了就直接说实际差多少, 下一步怎么调.
"#;

/// 追加上去的部分: 本局设置. 与内置 agent 一样, 通关走向与"一局结束后是否继续"由外部决定.
pub const AFTER_WIN_ENDLESS: &str = "\
本局通关 (打完底注 8 的 Boss) 之后继续无尽模式. 底注 9 起目标分涨得更快, 所以第 8 底注不是终点:
按一直打下去的打算来规划, 留住能继续成长的筹码与倍率来源, 保住经济和利息, 不要为了眼前过关丢掉
手牌上限, 出牌次数, 成长型小丑这类长期收益.";

pub const AFTER_WIN_MENU: &str = "\
本局通关 (打完底注 8 的 Boss) 之后就停. 目标是稳稳打完第 8 底注的 Boss, 不用为底注 9 之后留余量,
中期起可以把手里的资源换成当下的战力.";

/// 拼出完整的系统提示词.
///
/// `strategy` 是外部给的打法要求 (例如"优先买成长型小丑"), 与内置 agent 一样只在开头拼一次.
pub fn system(after_win_endless: bool, strategy: Option<&str>) -> String {
    let mut out = String::from(SYSTEM);
    out.push_str("\n## 本局设置\n");
    out.push_str(if after_win_endless {
        AFTER_WIN_ENDLESS
    } else {
        AFTER_WIN_MENU
    });
    if let Some(strategy) = strategy
        && !strategy.trim().is_empty()
    {
        out.push_str("\n\n## 玩家指定的策略\n");
        out.push_str(
            "下面是玩家给的打法要求. 选牌, 弃牌, 买卖, 经济这些决策按它来, 与上面的打法建议冲突时\
             以它为准; 规则要点仍按上面的写法.\n\n",
        );
        out.push_str(strategy.trim());
        out.push('\n');
    }
    out
}
