import assert from 'node:assert/strict';
import init, { Game, info } from '../impls/web/client/public/wasm/engine_lab.js';
import log from '../impls/web/client/src/lib/log';

const started = performance.now();
await init({ module_or_path: new Uint8Array(await Bun.file(new URL('../impls/web/client/public/wasm/engine_lab_bg.wasm', import.meta.url)).arrayBuffer()) });
const capabilities = JSON.parse(info());
if (process.argv[2]) assert.equal(capabilities.version, process.argv[2]);
const opening = JSON.stringify({ seed: 'ALEEB', deck: 'b_red', stake: 1, profile: 'all' });
const game = new Game(opening);
const dispatch = (kind: string, fields: object) => JSON.parse(game.dispatch(JSON.stringify({ kind, revision: JSON.parse(game.observe()).revision, ...fields })));
const deal = dispatch('action', { action: { method: 'select', params: {} } });
assert.equal(deal.observation.phase, 'SelectingHand');
assert.equal(deal.observation.hand.length, 8);
const beforeInvalid = game.observe();
assert.throws(() => dispatch('action', { action: { method: 'play', params: { cards: [999] } } }));
assert.equal(game.observe(), beforeInvalid);
const original = dispatch('action', { action: { method: 'play', params: { cards: [0] } } });
dispatch('jump', { node: 1 });
const branch = dispatch('action', { action: { method: 'play', params: { cards: [0] } } });
assert.equal(branch.history.length, 4);
assert.deepEqual(branch.observation, original.observation);
const restored = Game.restore(game.save());
assert.deepEqual(JSON.parse(restored.observe()).observation, branch.observation);
assert.match(restored.actions(), /"method":"start"/);
dispatch('debug', { enabled: true });
dispatch('edit', { changes: { dollars: 123 } });
assert.equal(JSON.parse(game.observe()).observation.stats.dollars, 123);
assert.throws(() => game.actions());
restored.free(); game.free();
log.info(`WASM 运行 smoke 通过, 版本 ${capabilities.version}, ${(performance.now() - started).toFixed(0)} ms`);
