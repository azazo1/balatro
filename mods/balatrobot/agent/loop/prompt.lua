内置 agent 的系统提示与固定用语. 纯逻辑, 不依赖游戏.

内容取自 docs/agent-commentary.md (解说规范) 与 docs/game/README.md 的 "Agent 必须区分的概念",
"每次动作前的规则检查" 两节, 压缩成模型用的版本. 那两份文档改动时同步这里.
